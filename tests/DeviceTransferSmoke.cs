// Explicit opt-in test against an already authorized device. Never reads personal files or clipboard.
using System;
using System.IO;
using System.Linq;
using System.Threading;
using System.Threading.Tasks;
using Morror;

class DeviceTransferSmoke
{
    static int Main(string[] args)
    {
        try { Run(args).GetAwaiter().GetResult(); return 0; }
        catch (Exception error) { Console.Error.WriteLine(error.Message); return 1; }
    }
    static async Task Run(string[] args)
    {
        if (args.Length != 4) throw new ArgumentException("Usage: DeviceTransferSmoke adb serial test.png output-folder");
        var transfer = new FileTransfer(args[0],args[1]);
        TransferReceipt receipt = null;
        try
        {
            receipt = await transfer.Push(args[2],CancellationToken.None);
            Console.WriteLine("PASS Upload size verified: " + receipt.Bytes);
            if (string.IsNullOrEmpty(receipt.MediaUri)) throw new Exception("File delivered, but media indexing did not confirm a URI.");
            Console.WriteLine("PASS Android media index returned an openable content URI");
            string destination = FileTransfer.NewLocalPath(args[3],"phone-roundtrip.png");
            await transfer.Pull(receipt.Path,destination,CancellationToken.None);
            if (!File.ReadAllBytes(args[2]).SequenceEqual(File.ReadAllBytes(destination))) throw new Exception("Round-trip bytes differ.");
            Console.WriteLine("PASS Phone-to-PC download matches the original PNG byte for byte");
        }
        finally
        {
            if (receipt != null)
            {
                // Only the unique path generated by this test; never delete a user's source.
                Cleanup(receipt, args).GetAwaiter().GetResult();
            }
        }
    }
    static async Task Cleanup(TransferReceipt receipt, string[] args)
    {
        await Commands.Run(args[0],10000,"-s",args[1],"shell","rm -f -- " + FileTransfer.ShellQuote(receipt.Path));
        await Commands.Run(args[0],10000,"-s",args[1],"shell","content call --uri content://media --method scan_file --arg " + FileTransfer.ShellQuote(receipt.Path));
        Console.WriteLine("Removed only the generated phone test file.");
    }
}
